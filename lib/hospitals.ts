export function getHospitalDetails(hospitalName: string): HospitalInfo | null {
  if (!hospitalName) return null;
  const match = CHATTOGRAM_HOSPITALS.find(
    (h) => h.name.toLowerCase().trim() === hospitalName.toLowerCase().trim()
  );
  return match || null;
}
